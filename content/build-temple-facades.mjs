/**
 * B2 — Facades web do Templo (`src/data/temple/`), com LAZY CHUNKS por domínio
 * de conceito (decisão #10 do plano — os 7,2 MB de conceitos NUNCA entram no
 * bundle inicial).
 *
 * Saída:
 *   src/data/temple/concepts/<domainId>.json     12 chunks (~600 KB cada)
 *   src/data/temple/concept-index.json           índice leve dos 225 conceitos
 *   src/data/temple/techniques.json              categorias + técnicas
 *   src/data/temple/authors.json                 autores curados
 *   src/data/temple/approachRegistry.json        registro canônico de abordagens
 *   src/data/temple/conceptChunks.ts             manifest split (leve)        [gerado]
 *   src/data/temple/conceptIndex.ts              facade index (chunk próprio) [gerado]
 *   src/data/temple/registry.ts                  facade do registry           [gerado]
 *   src/data/temple/authors.ts                   facade autores               [gerado]
 *   src/data/temple/techniques.ts                facade técnicas              [gerado]
 *   src/data/temple/comparisons.ts               facade comparações           [gerado]
 *
 * Nada de `index.ts` monolítico: o loader (`src/lib/templeData.ts`) importa
 * CADA dataset em seu próprio chunk, então abrir "conceitos" baixa só o índice
 * (~100 KB) em vez dos antigos ~5 MB de tudo junto.
 */

import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'path';
import { ROOT, loadConceptFiles, loadTechniques } from './temple-lib.mjs';
import { loadComparisonSqlSources } from './comparations/normalizer.mjs';

const OUT = path.join(ROOT, 'src', 'data', 'temple');

/** Corpo exibível do conceito no detalhe (mantido integral p/ fidelidade editorial). */
function conceptChunkEntry(data) {
  return {
    id: data.id,
    name: data.name,
    slug: data.slug ?? null,
    domainId: data.domainId,
    domainName: data.domainName ?? null,
    definition: data.definition ?? '',
    sections: data.sections ?? {},
    authorIds: data.authorIds ?? [],
    approachIds: data.approachIds ?? [],
    topicIds: data.topicIds ?? [],
    relatedConceptIds: data.relatedConceptIds ?? [],
    relationStatus: data.relationStatus ?? null,
    status: data.status ?? null,
    reviewStatus: data.reviewStatus ?? null,
  };
}

/** Gera os facades TS split (um módulo por dataset — sem `index.ts` monolítico). */
function writeFacades(outDir, domains, domainIds) {
  const domainListJson = JSON.stringify(
    domainIds.map((d) => ({ id: d, name: domains.get(d).name }))
  );

  const conceptChunks = `// GENERATED BY content/build-temple-facades.mjs — NÃO EDITAR MANUALMENTE.
// Manifest de conceitos (split): leve, pode entrar no bundle base. O índice e
// os corpos por domínio continuam em chunks próprios carregados sob demanda.
import type { TempleConcept } from '../../types';

export interface ConceptDomainInfo {
  id: string;
  name: string;
}

const CONCEPT_DOMAINS: ConceptDomainInfo[] = ${domainListJson};

const CONCEPT_CHUNKS: Record<string, () => Promise<{ default: TempleConcept[] }>> = {
${domainIds
  .map(
    (d) => `  '${d}': async (): Promise<{ default: TempleConcept[] }> => {
    const chunk = await import('./concepts/${d}.json');
    return { default: chunk.default as unknown as TempleConcept[] };
  },`
  )
  .join('\n\n')}
};

export const conceptDomains = CONCEPT_DOMAINS;

export function conceptChunkLoader(domainId: string) {
  return CONCEPT_CHUNKS[domainId] ?? null;
}
`;

  const conceptIndex = `// GENERATED BY content/build-temple-facades.mjs — NÃO EDITAR MANUALMENTE.
import conceptIndexJson from './concept-index.json' with { type: 'json' };

export interface ConceptIndexEntry {
  id: string;
  name: string;
  domainId: string;
  domainName: string | null;
  definition: string;
}

export const conceptIndex = conceptIndexJson as ConceptIndexEntry[];
`;

  const registry = `// GENERATED BY content/build-temple-facades.mjs — NÃO EDITAR MANUALMENTE.
import registryJson from './approachRegistry.json' with { type: 'json' };

export interface ApproachRegistryFile {
  schemaVersion: number;
  generatedAt: string;
  stats: Record<string, number>;
  entries: Array<{
    id: string;
    name: string;
    system: string;
    familyId: string | null;
    aliases: Array<{ id: string; source: string; packageName?: string }>;
    taxonomyFamilyId?: string | null;
  }>;
  resolve: Record<string, string>;
}

export const approachRegistryFile = registryJson as unknown as ApproachRegistryFile;

/** Resolve qualquer id de abordagem (editorial/taxonomic/técnicas) → canônica. */
export function resolveApproach(aliasId: string):
  | { id: string; name: string; familyId: string | null }
  | null {
  const canonicalId = approachRegistryFile.resolve[aliasId];
  if (!canonicalId) return null;
  const entry = approachRegistryFile.entries.find((e) => e.id === canonicalId);
  if (!entry) return null;
  return { id: entry.id, name: entry.name, familyId: entry.familyId };
}
`;

  const authors = `// GENERATED BY content/build-temple-facades.mjs — NÃO EDITAR MANUALMENTE.
import type { TempleAuthor } from '../../types';
import authorsJson from './authors.json' with { type: 'json' };

export interface CuratedAuthorsFile {
  schemaVersion: number;
  generatedAt: string;
  stats: Record<string, number>;
  families: string[];
  authors: TempleAuthor[];
}

export const curatedAuthorsFile = authorsJson as unknown as CuratedAuthorsFile;
`;

  const techniques = `// GENERATED BY content/build-temple-facades.mjs — NÃO EDITAR MANUALMENTE.
import type { TempleTechnique, TempleTechniqueCategory } from '../../types';
import techniquesJson from './techniques.json' with { type: 'json' };

interface TechniquesFile {
  categories: TempleTechniqueCategory[];
  techniques: TempleTechnique[];
}

export const techniqueCategories = (techniquesJson as unknown as TechniquesFile).categories;
export const templeTechniques = (techniquesJson as unknown as TechniquesFile).techniques;
`;

  const comparisons = `// GENERATED BY content/build-temple-facades.mjs — NÃO EDITAR MANUALMENTE.
import type { TempleComparison } from '../../types';
import comparisonsJson from './comparisons.json' with { type: 'json' };

export interface ComparisonsFile {
  schemaVersion: number;
  generatedAt: string;
  scope: string;
  counts: Record<string, number>;
  canonicalAxes: string[];
  schemaNotes: string[];
  fontes: Array<Record<string, unknown>>;
  comparacoes: TempleComparison[];
}

export const comparisonsFile = comparisonsJson as unknown as ComparisonsFile;
`;

  writeFileSync(path.join(outDir, 'conceptChunks.ts'), conceptChunks);
  writeFileSync(path.join(outDir, 'conceptIndex.ts'), conceptIndex);
  writeFileSync(path.join(outDir, 'registry.ts'), registry);
  writeFileSync(path.join(outDir, 'authors.ts'), authors);
  writeFileSync(path.join(outDir, 'techniques.ts'), techniques);
  writeFileSync(path.join(outDir, 'comparisons.ts'), comparisons);
}

async function main() {
  const conceptFiles = loadConceptFiles();
  const domains = new Map(); // domainId -> {id, name}
  const byDomain = new Map(); // domainId -> entries[]
  const index = [];

  for (const { data } of conceptFiles) {
    if (!domains.has(data.domainId)) {
      domains.set(data.domainId, {
        id: data.domainId,
        name: data.domainName ?? data.domainId,
      });
      byDomain.set(data.domainId, []);
    }
    const entry = conceptChunkEntry(data);
    byDomain.get(data.domainId).push(entry);
    index.push({
      id: entry.id,
      name: entry.name,
      domainId: entry.domainId,
      domainName: entry.domainName,
      definition: String(entry.definition ?? '').slice(0, 220),
    });
  }

  const domainIds = [...domains.keys()].sort();
  mkdirSync(path.join(OUT, 'concepts'), { recursive: true });

  for (const domainId of domainIds) {
    writeFileSync(
      path.join(OUT, 'concepts', `${domainId}.json`),
      JSON.stringify(byDomain.get(domainId))
    );
  }
  writeFileSync(path.join(OUT, 'concept-index.json'), JSON.stringify(index));

  // ---- autores (fichas curadas) / registry / técnicas ----
  const authors = JSON.parse(
    readFileSync(path.join(ROOT, 'content', 'editorial', 'authorsCurated.json'), 'utf8')
  );
  writeFileSync(path.join(OUT, 'authors.json'), JSON.stringify(authors));

  const registry = JSON.parse(
    readFileSync(path.join(ROOT, 'content', 'editorial', 'approachRegistry.json'), 'utf8')
  );
  writeFileSync(path.join(OUT, 'approachRegistry.json'), JSON.stringify(registry));

  const { categories, techniques } = await loadTechniques();
  writeFileSync(
    path.join(OUT, 'techniques.json'),
    JSON.stringify({ categories, techniques })
  );

  const comparisons = loadComparisonSqlSources(
    path.join(ROOT, 'content', 'comparations', 'migrations', 'comparacoes_seed_completo.sql'),
    readFileSync
  );
  writeFileSync(path.join(OUT, 'comparisons.json'), JSON.stringify(comparisons));

  // ---- facades TS split (gerados aqui; loader importa cada dataset em chunk) ----
  writeFacades(OUT, domains, domainIds);

  console.log(
    `[temple-facades] ${index.length} conceitos · ${domainIds.length} chunks · ` +
      `${authors.authors.length} fichas de autor · ${techniques.length} técnicas`
  );
}

main().catch((e) => {
  console.error('[temple-facades] falhou:', e);
  process.exit(1);
});
